interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  toggleLanguage: () => void;
  isRtl: boolean;
  dir: 'rtl' | 'ltr';
  t: (key: string, params?: Record<string, string | number>) => string;
  formatNumber: (num: number | string) => string;
  formatCurrency: (amount: number | string, unit?: 'IRT' | 'IRR') => string;
  formatDate: (dateInput?: string | Date | null, includeTime?: boolean) => string;
  formatShortDate: (dateInput?: string | Date | null) => string;
  formatRelativeTime: (dateInput?: string | Date | null) => string;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

const LANGUAGE_STORAGE_KEY = 'sarv_crm_lang';

export const getInitialLanguage = (): Language => {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === 'en' || saved === 'fa') return saved;
  } catch (e) {
    // ignore
  }
  return 'fa'; // Persian by default
};

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);

  const applyLanguageToDom = useCallback((lang: Language) => {
    const isRtl = lang === 'fa';
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    if (isRtl) {
      document.documentElement.classList.add('rtl');
      document.documentElement.classList.remove('ltr');
    } else {
      document.documentElement.classList.add('ltr');
      document.documentElement.classList.remove('rtl');
    }
  }, []);

  useEffect(() => {
    applyLanguageToDom(language);
  }, [language, applyLanguageToDom]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    } catch (e) {
      // ignore
    }
    applyLanguageToDom(lang);
  };

  const toggleLanguage = () => {
    setLanguage(language === 'fa' ? 'en' : 'fa');
  };

  useEffect(() => {
    const handleStorageChange = (e: StorageEvent) => {
      if (e.key === LANGUAGE_STORAGE_KEY && (e.newValue === 'fa' || e.newValue === 'en')) {
        setLanguageState(e.newValue as Language);
        applyLanguageToDom(e.newValue as Language);
      }
    };
    window.addEventListener('storage', handleStorageChange);
    return () => window.removeEventListener('storage', handleStorageChange);
  }, [language, applyLanguageToDom]);

  const isRtl = language === 'fa';
  const dir = isRtl ? 'rtl' : 'ltr';

  const t = useCallback((key: string, params?: Record<string, string | number>): string => {
    const dict = language === 'fa' ? faTranslations : enTranslations;
    let text = dict[key] || faTranslations[key] || enTranslations[key] || key;
    if (params) {
      Object.entries(params).forEach(([paramKey, value]) => {
        text = text.replace(new RegExp(`{${paramKey}}`, 'g'), String(value));
      });
    }
    return text;
  }, [language]);

  const formatNumber = useCallback((num: number | string): string => {
    if (num === undefined || num === null) return '';
    const str = num.toString();
    return toEnglishDigits(str);
  }, []);

  const formatCurrency = useCallback((amount: number | string, unit: 'IRT' | 'IRR' = 'IRT'): string => {
    if (amount === undefined || amount === null || isNaN(Number(amount))) {
      return language === 'fa' ? '۰ تومان' : '0 Toman';
    }
    const num = Math.round(Number(amount));
    const formatted = num.toLocaleString('en-US');
    if (language === 'fa') {
      return `${formatted} ${unit === 'IRT' ? 'تومان' : 'ریال'}`;
    }
    return `${formatted} ${unit === 'IRT' ? 'Toman' : 'IRR'}`;
  }, [language]);

  const formatDate = useCallback((dateInput?: string | Date | null, includeTime?: boolean): string => {
    if (language === 'fa') {
      return dateInput === undefined ? '' : formatPersianDate(dateInput, includeTime ?? true);
    }
    return dateInput === undefined ? '' : formatGregorianDate(dateInput, includeTime ?? true);
  }, [language]);

  const formatShortDate = useCallback((dateInput?: string | Date | null): string => {
    if (dateInput === undefined || dateInput === null) return '';
    if (language === 'fa') return formatPersianShortDate(dateInput);
    return formatGregorianShortDate(dateInput);
  }, [language]);

  const formatRelativeTime = useCallback((dateInput?: string | Date | null): string => {
    if (dateInput === undefined || dateInput === null) return '';
    return language === 'fa' ? getRelativeTimeFa(dateInput) : getRelativeTimeEn(dateInput);
  }, [language]);

  return React.createElement(
    I18nContext.Provider,
    {
      value: {
        language,
        setLanguage,
        toggleLanguage,
        isRtl,
        dir,
        t,
        formatNumber,
        formatCurrency,
        formatDate,
        formatShortDate,
        formatRelativeTime,
      },
    },
    children
  );
};

export const useTranslation = (): I18nContextType => {
  const context = useContext(I18nContext);
  if (!context) {
    const lang = getInitialLanguage();
    const isRtl = lang === 'fa';
    return {
      language: lang,
      setLanguage: () => {},
      toggleLanguage: () => {},
      isRtl,
      dir: isRtl ? 'rtl' : 'ltr',
      t: (key: string) => (lang === 'fa' ? faTranslations[key] || key : enTranslations[key] || key),
      formatNumber: (n) => (lang === 'fa' ? toPersianDigits(String(n)) : toEnglishDigits(String(n))),
      formatCurrency: (a) => (lang === 'fa' ? `${toPersianDigits(Number(a).toLocaleString())} تومان` : `${Number(a).toLocaleString()} Toman`),
      formatDate: (d, incTime) => (d === undefined ? '' : (lang === 'fa' ? formatPersianDate(d, incTime ?? true) : formatGregorianDate(d, incTime ?? true))),
      formatShortDate: (d) => (d === undefined || d === null ? '' : (lang === 'fa' ? formatPersianShortDate(d) : formatGregorianShortDate(d))),
      formatRelativeTime: (d) => (d === undefined || d === null ? '' : (lang === 'fa' ? getRelativeTimeFa(d) : getRelativeTimeEn(d))),
    };
  }
  return context;
};
